"""Regenerate recomp-ui's five-language UI table from translations.py.

    python tools/i18n/emit.py

Columns: English, French, German, Spanish, Italian. Format specifiers must
match the English text. To find untranslated strings, run TempleFrog with
RECOMP_UI_I18N_MISSES=<file> in a non-English language (Game > Language).
"""
import pathlib
import sys

here = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(here))
from translations import T  # noqa: E402


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ["// {English, French, German, Spanish, Italian}. Generated by TempleFrog's",
         "// tools/i18n/emit.py; keep format specifiers identical across columns."]
for en, cols in sorted(T.items(), key=lambda kv: kv[0].lower()):
    for col in cols:
        assert col.count("%") == en.count("%"), en
    lines.append("{%s, %s, %s, %s, %s}," % ((c(en),) + tuple(c(x) for x in cols)))
out = here.parents[1] / "recomp-ui/src/common/launcher_i18n_strings.inc"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("rows", len(T), "->", out)
